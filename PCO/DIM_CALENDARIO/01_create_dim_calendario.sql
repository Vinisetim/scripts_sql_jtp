CREATE TABLE DIM_CALENDARIO(
    ID_CALENDARIO INT PRIMARY KEY,
    DATA_COMPLETA DATE,
    ANO INT,
    MES INT,
    DIA INT,
    NOME_MES VARCHAR(20),
    NOME_ABREV VARCHAR(5),
    TRIMESTRE INT,
    DIA_SEMANA INT, 
    NOME_DIA_SEMANA VARCHAR(20),
    TIPO_DIA_PADRAO VARCHAR(15)
);

CREATE VIEW VW_DIM_CALENDARIO AS
SELECT 
    ID_CALENDARIO,
    DATA_COMPLETA,
    ANO,
    MES,
    DIA,
    NOME_MES,
    NOME_ABREV,
    TRIMESTRE,
    DIA_SEMANA,
    NOME_DIA_SEMANA,
    TIPO_DIA_PADRAO,
    CASE 
        WHEN DATA_COMPLETA <= CAST(DATEADD(HOUR, -3, GETDATE()) AS DATE) THEN 1 
        ELSE 0 
    END AS FLG_PASSADO
FROM DIM_CALENDARIO;
