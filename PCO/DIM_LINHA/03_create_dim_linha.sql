CREATE TABLE DIM_LINHA(
    ID_LINHA INT IDENTITY(1,1) PRIMARY KEY,
    CODIGO_SISTEMA VARCHAR(20) NOT NULL,
    NOME_LINHA_NORMALIZADO VARCHAR(100),
    GRUPO_LINHA VARCHAR(50),
    KM_PREVISTO_IDA DECIMAL(10,2),
    KM_PREVISTO_VOLTA DECIMAL(10,2),
    OPERACAO_RESPONSAVEL VARCHAR(50), 
    KM_CICLO_PREVISTO DECIMAL(10,2),
    );